export function getManualStatsSummary(): {
  departmentsCount: number;
  tabsCount: number;
  buttonsCount: number;
  equationsCount: number;
} {
  const departmentsCount = MANUAL_DEPARTMENTS.length;
  const tabsCount = MANUAL_DEPARTMENTS.reduce((sum, d) => sum + d.tabs.length, 0);
  const buttonsCount = MANUAL_BUTTON_GROUPS.reduce((sum, g) => sum + g.buttons.length, 0);
  const equationsCount = MANUAL_EQUATION_GROUPS.reduce((sum, g) => sum + g.equations.length, 0);
  return { departmentsCount, tabsCount, buttonsCount, equationsCount };
}

export function normalizeArabicSearch(text: string): string {
  return String(text || '')
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u064B-\u065F]/g, '')
    .trim();
}

export function filterManualDepartments(
  query: string,
  departmentIdFilter: string = 'all'
): ManualDepartmentDoc[] {
  const q = normalizeArabicSearch(query);
  return MANUAL_DEPARTMENTS.filter((dept) => {
    if (departmentIdFilter !== 'all' && dept.id !== departmentIdFilter) return false;
    if (!q) return true;
    const deptHay = normalizeArabicSearch(`${dept.title} ${dept.subtitle} ${dept.overview}`);
    if (deptHay.includes(q)) return true;
    return dept.tabs.some((t) =>
      normalizeArabicSearch(`${t.label} ${t.purpose} ${t.keyActions.join(' ')}`).includes(q)
    );
  }).map((dept) => {
    if (!q) return dept;
    const deptHay = normalizeArabicSearch(`${dept.title} ${dept.subtitle} ${dept.overview}`);
    if (deptHay.includes(q)) return dept;
    return {
      ...dept,
      tabs: dept.tabs.filter((t) =>
        normalizeArabicSearch(`${t.label} ${t.purpose} ${t.keyActions.join(' ')}`).includes(q)
      ),
    };
  });
}

export function filterManualButtons(query: string): ManualButtonGroup[] {
  const q = normalizeArabicSearch(query);
  if (!q) return MANUAL_BUTTON_GROUPS;
  return MANUAL_BUTTON_GROUPS.map((group) => ({
    ...group,
    buttons: group.buttons.filter((b) =>
      normalizeArabicSearch(`${group.title} ${b.name} ${b.location} ${b.functionDesc} ${b.behaviorNote}`).includes(q)
    ),
  })).filter((g) => g.buttons.length > 0);
}

export function filterManualEquations(
  query: string,
  groupIdFilter: string = 'all'
): ManualEquationGroup[] {
  const q = normalizeArabicSearch(query);
  return MANUAL_EQUATION_GROUPS.filter((group) => {
    if (groupIdFilter !== 'all' && group.id !== groupIdFilter) return false;
    return true;
  })
    .map((group) => {
      if (!q) return group;
      const groupHit = normalizeArabicSearch(`${group.title} ${group.subtitle}`).includes(q);
      if (groupHit) return group;
      return {
        ...group,
        equations: group.equations.filter((eq) =>
          normalizeArabicSearch(
            `${eq.code} ${eq.name} ${eq.department} ${eq.formula} ${eq.variables} ${eq.workedExample} ${eq.guardRule}`
          ).includes(q)
        ),
      };
    })
    .filter((g) => g.equations.length > 0);
}

export function buildManualPdfFilename(customName?: string, scope: ManualScope = 'full'): string {
  const dateStr = new Date().toISOString().slice(0, 10);
  const scopeSuffix =
    scope === 'equations_only'
      ? 'المعادلات_الحسابية'
      : scope === 'departments_buttons'
      ? 'الاقسام_والازرار'
      : 'الشامل';
  const raw = (customName || '').trim() || `دليل_المستخدم_${scopeSuffix}_منظومة_التموين_${dateStr}`;
  const cleaned = raw
    .replace(/\.pdf$/i, '')
    .replace(/[<>:"/\\|?*\u0000-\u001F]+/g, '_')
    .replace(/\s+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 90);
  return `${cleaned || `دليل_المستخدم_${dateStr}`}.pdf`;
}

function escapeHtml(raw: string): string {
  return String(raw || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

